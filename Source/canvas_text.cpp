double Canvas::text_width(const std::string& s, double size_px) const {
    const double unit = size_px / 6.0;
    double w = 0.0;
    for (char32_t c : decode(s)) w += place(c).advance;
    if (w > 0.0) w -= 1.2;
    return w * unit;
}

void Canvas::text(Vec2 screen, const std::string& s, double size_px, Color c, TextAlign align, double weight) {
    if (s.empty() || !(size_px > 0.0)) return;
    const double unit = size_px / 6.0;
    const double width = text_width(s, size_px);
    double x = screen.x;
    if (align == TextAlign::Center) x -= 0.5 * width;
    else if (align == TextAlign::Right) x -= width;
    const double baseline = screen.y;
    const double stroke = std::max(1.0, size_px * 0.11 * weight);
    for (char32_t ch : decode(s)) {
        const Placed p = place(ch);
        if (p.glyph) {
            const double u = unit * p.scale;
            const double base = baseline - p.dy * unit;
            const char* q = p.glyph->strokes;
            std::vector<double> nums;
            const auto flush = [&]() {
                if (nums.size() >= 4) {
                    for (std::size_t k = 0; k + 3 < nums.size(); k += 2) {
                        const Vec2 a{ x + nums[k] * u, base - nums[k + 1] * u };
                        const Vec2 b{ x + nums[k + 2] * u, base - nums[k + 3] * u };
                        capsule(a, b, 0.5 * stroke * (p.scale < 1.0 ? 0.85 : 1.0), c);
                    }
                }
                nums.clear();
            };
            while (*q) {
                if (*q == ';') {
                    flush();
                    ++q;
                    continue;
                }
                if (*q == ' ') {
                    ++q;
                    continue;
                }
                char* end = nullptr;
                const double v = std::strtod(q, &end);
                if (end == q) {
                    ++q;
                    continue;
                }
                nums.push_back(v);
                q = end;
            }
            flush();
        } else if (ch != U' ') {
            stroke_rect_px(x + 0.3 * unit, baseline - 6.0 * unit, 3.4 * unit, 6.0 * unit, c, 1.0);
        }
        x += p.advance * unit;
    }
}

