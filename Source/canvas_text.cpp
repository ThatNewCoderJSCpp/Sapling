const Glyph* glyph_of(char32_t c) {
    for (const Glyph& g : GLYPHS) {
        if (g.code == c) return &g;
    }
    return nullptr;
}

std::vector<char32_t> decode(const std::string& s) {
    std::vector<char32_t> out;
    for (std::size_t i = 0; i < s.size();) {
        const unsigned char c = static_cast<unsigned char>(s[i]);
        char32_t cp = 0;
        int extra = 0;
        if (c < 0x80) {
            cp = c;
        } else if ((c & 0xE0) == 0xC0) {
            cp = c & 0x1F;
            extra = 1;
        } else if ((c & 0xF0) == 0xE0) {
            cp = c & 0x0F;
            extra = 2;
        } else {
            cp = c & 0x07;
            extra = 3;
        }
        ++i;
        for (int k = 0; k < extra && i < s.size(); ++k, ++i) cp = (cp << 6) | (static_cast<unsigned char>(s[i]) & 0x3F);
        out.push_back(cp);
    }
    return out;
}

struct Placed {
    const Glyph* glyph;
    double scale;
    double dy;
    double advance;
};

Placed place(char32_t c) {
    for (const Script& s : SCRIPTS) {
        if (s.code == c) {
            const Glyph* g = glyph_of(s.base);
            const double sc = 0.62;
            return Placed{ g, sc, s.kind == 1 ? 3.6 : -1.6, (g ? g->width : 3.0) * sc + 0.8 };
        }
    }
    if (c == U' ') return Placed{ nullptr, 1.0, 0.0, 3.0 };
    const Glyph* g = glyph_of(c);
    if (!g) return Placed{ nullptr, 1.0, 0.0, 4.5 };
    return Placed{ g, 1.0, 0.0, g->width + 1.2 };
}

